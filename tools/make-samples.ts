/** Builds src/adapters/samples/data.ts: the bundled synthetic sample statements as base64 (no fetch needed under connect-src 'none'). */
import fs from 'node:fs';
import { generate } from './synth/generate';

const defs = [
  { id: 'bank-clean', layout: 'bank-signed', seed: 11, title: 'Checking statement', note: 'Single page, signed amounts, running balance. Reconciles.', opts: {} },
  { id: 'card', layout: 'cc-two-date', seed: 12, title: 'Credit-card statement', note: 'Two date columns, payments and purchases in separate sections. Reconciles.', opts: {} },
  { id: 'multipage', layout: 'bank-multipage', seed: 13, title: 'Multi-page checking statement', note: 'Three pages, repeated headers, debit/credit columns. Reconciles.', opts: {} },
  { id: 'missing-line', layout: 'bank-debit-credit', seed: 14, title: 'Statement with a missing line', note: 'One transaction is absent from the PDF itself. Shows the red DISCREPANCY state and the pinpointed row.', opts: { omitRow: 9 } },
  { id: 'protected', layout: 'bank-password', seed: 15, title: 'Password-protected statement', note: 'Password: ledger123', opts: {}, password: 'ledger123' },
] as const;
const out = [];
for (const d of defs) {
  const g = await generate(d.layout, d.seed, d.opts);
  out.push({ id: d.id, title: d.title, note: d.note, fileName: `${d.layout}-sample.pdf`, password: 'password' in d ? d.password : undefined, base64: Buffer.from(g.pdf).toString('base64') });
}
const ts = `// GENERATED by tools/make-samples.ts - synthetic statements from fictional banks. Do not edit.\nexport interface Sample { id: string; title: string; note: string; fileName: string; password?: string; base64: string }\nexport const SAMPLES: Sample[] = ${JSON.stringify(out, null, 2)};\n`;
fs.mkdirSync('src/adapters/samples', { recursive: true });
fs.writeFileSync('src/adapters/samples/data.ts', ts);
console.log(`samples: ${out.length}, ${(ts.length / 1024).toFixed(1)} KB source`);
